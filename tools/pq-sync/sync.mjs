#!/usr/bin/env node
// Copies the analyzer's instrument models into every KISEM app that reads logger files, so a model
// added or changed here reaches the apps with one command. See docs/INSTRUMENT-MODELS.md.
//
//   node tools/pq-sync/sync.mjs           write the models (and the shared reader) into each app
//   node tools/pq-sync/sync.mjs --check   only say which apps are out of date (exit 1 if any)
//
// Source of truth: backend/config/mappings/<MODEL>.json (the *_custom_columns.json files are the
// analyzer's own and are not copied). Each app gets lib/pq-mappings/<slug>.json for every model and
// a generated lib/pq-mappings/index.ts listing them; apps marked "reader" also get lib/pq-read.ts.
// After a sync, commit and push each app: its server build makes the new APK and web app.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const SRC = path.join(repo, 'backend/config/mappings');
const check = process.argv.includes('--check');
const { targets, models: overrides } = JSON.parse(fs.readFileSync(path.join(here, 'targets.json'), 'utf8'));

// Every model file, once (a lower-case copy of an upper-case file, like alm31.json, is skipped).
const files = fs.readdirSync(SRC).filter(f => f.endsWith('.json') && !f.endsWith('_custom_columns.json')).sort();
const slugOf = f => f.replace(/\.json$/, '').toLowerCase().replace(/[^a-z0-9]/g, '');
const models = [];
for (const f of files) {
  const base = f.replace(/\.json$/, '');
  if (base === base.toLowerCase() && files.some(g => g !== f && slugOf(g) === slugOf(f))) continue;
  const o = overrides[base] || {};
  const id = o.id || base.replace(/_/g, ' ');
  const kind = o.kind || (/clamp/i.test(base) ? 'Clamp' : 'PQ');
  models.push({ file: f, id, slug: o.slug || slugOf(f), kind, label: o.label || `${id} (${kind === 'Clamp' ? 'clamp meter' : 'PQ analyser'})` });
}

const index = [
  '// GENERATED by ai-power-quality-analyzer/tools/pq-sync/sync.mjs from backend/config/mappings.',
  '// Do not edit here: add or change the model in the analyzer and run the sync (docs/INSTRUMENT-MODELS.md).',
  ...models.map(m => `import ${m.slug} from "./${m.slug}.json";`),
  '',
  'export type PqMappingValue = string | { standard_column: string; source_page?: string };',
  'export type PqMapping = Record<string, PqMappingValue>;',
  'export type PqModel = { id: string; label: string; kind: "PQ" | "Clamp"; mapping: PqMapping };',
  '',
  'export const PQ_MODELS: PqModel[] = [',
  ...models.map(m => `  { id: ${JSON.stringify(m.id)}, label: ${JSON.stringify(m.label)}, kind: "${m.kind}", mapping: ${m.slug} as PqMapping },`),
  '];',
  '',
].join('\n');
const reader = fs.readFileSync(path.join(here, 'pq-read.ts'), 'utf8');

let stale = 0;
for (const t of targets) {
  const lib = path.resolve(repo, t.dir);
  if (!fs.existsSync(lib)) { console.log(`skip ${t.app}: ${lib} not found`); continue; }
  const want = new Map();
  for (const m of models) want.set(path.join(lib, 'pq-mappings', `${m.slug}.json`), fs.readFileSync(path.join(SRC, m.file), 'utf8'));
  want.set(path.join(lib, 'pq-mappings', 'index.ts'), index);
  if (t.reader) want.set(path.join(lib, 'pq-read.ts'), reader);
  // Git on Windows may check files out with CRLF: compare without line endings.
  const lf = (x) => x.replace(/\r\n/g, '\n');
  const changed = [...want].filter(([p, body]) => !fs.existsSync(p) || lf(fs.readFileSync(p, 'utf8')) !== lf(body));
  if (!changed.length) { console.log(`ok   ${t.app}: up to date (${models.length} models)`); continue; }
  stale++;
  console.log(`${check ? 'OLD ' : 'sync'} ${t.app}: ${changed.map(([p]) => path.relative(lib, p)).join(', ')}`);
  if (!check) for (const [p, body] of changed) { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, body); }
}
console.log(`${models.length} models: ${models.map(m => m.id).join(', ')}`);
if (check && stale) process.exit(1);
